"""Sweep analysis (no API calls). Reads logs/sweep/*.jsonl, writes reports/sweep_results.md + .json.

Knob metric: recall@k at the config's own k (k = 5 except the top-k axis), raw AND above random
(recall - mean chance@k). Bootstrap 95% CIs: 2000 question-level resamples, default_rng(0).
Ranking pool: Tier A main (n = 33, covers the corpus) is primary. Tier B (Chinese) is reported beside it.
This pool choice is made here, before reading any sweep number, and was not in the pre-registration.
A/B readout (writeup_notes scoring plan, at the base config):
  (1) Tier A main, (2) Tier B retrieval-scored (11 standard + B09 + B14, strict and lenient),
  (3) Tier A on the sections Tier B covers: main questions in those sections + the top-up; gold-only sensitivity.
  recall@5, MRR@5 and median uncensored rank, each with n and a bootstrap CI. Descriptive only (pre-registered).
"""
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
import sys  # noqa: E402
sys.path.insert(0, str(ROOT))
from rag.chunker import measured_overlap  # noqa: E402
from rag.index import INDEX_DIR, index_name  # noqa: E402
from rag.sections import _groups, gold_ids, load_eval_set  # noqa: E402
from rag.sweep_plan import RUNS, config_for  # noqa: E402

rng = np.random.default_rng(0)
NB = 2000


def boot(x):
    x = np.asarray(x, float)
    if len(x) == 0:
        return (np.nan, np.nan, np.nan)
    m = rng.integers(0, len(x), (NB, len(x)))
    b = x[m].mean(1)
    return (float(x.mean()), float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5)))


def fmt(t, pct=True):
    s = 100 if pct else 1
    return f"{s * t[0]:.0f} [{s * t[1]:.0f}, {s * t[2]:.0f}]" if pct else f"{t[0]:.2f} [{t[1]:.2f}, {t[2]:.2f}]"


def load(run):
    return [json.loads(l) for l in open(ROOT / f"logs/sweep/{run}.jsonl")]


def scored(recs, rule="strict"):
    return [r for r in recs if rule in r]


def main():
    data = {rid: load(rid) for rid, _, _ in RUNS}
    out = {"knobs": {}, "ab": {}, "paired": {}, "answers": {}}
    L = ["# Sweep results (generated by scripts/analyze_sweep.py; descriptive; bootstrap 95% CIs)\n"]

    # ---------------- knob table
    L.append("## Knob table: recall@k at the config's k (k=5 except the top-k axis)\n")
    L.append("| run | axis | cs | overlap measured | k | pool | n | recall@k | chance@k | above random | MRR@k |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for rid, axis, _ in RUNS:
        cfg, _ = config_for(rid)
        meta = json.loads((INDEX_DIR / index_name(cfg["model"], cfg) / "meta.json").read_text())
        ov = meta["overlap_measured"]["pct"]
        k = cfg["k"]
        for pool in ("A_main", "B"):
            rs = [r for r in scored(data[rid]) if r["pool"] == pool]
            hit = [r["strict"][f"hit@{k}"] for r in rs]
            ch = [r["strict"][f"chance@{k}"] for r in rs]
            rr = [r["strict"][f"rr@{k}"] for r in rs]
            above = boot(np.array(hit, float) - np.array(ch))
            out["knobs"][f"{rid}|{pool}"] = {"recall": boot(hit), "chance": float(np.mean(ch)), "above": above,
                                             "mrr": boot(rr), "n": len(rs), "overlap_measured": ov, "k": k,
                                             "cs": cfg["chunk_size"]}
            L.append(f"| {rid} | {axis} | {cfg['chunk_size']} | {ov:.1f}% | {k} | {pool} | {len(rs)} | "
                     f"{fmt(boot(hit))} | {100 * np.mean(ch):.0f} | {fmt(above)} | {fmt(boot(rr), False)} |")

    # ---------------- knob ranking (effect vs base, largest |delta| along each axis)
    L.append("\n## Knob ranking: largest |change from base| along each axis\n")
    L.append("| pool | metric | chunk_size | overlap | top_k | ranking |")
    L.append("|---|---|---|---|---|---|")
    axes = {"chunk_size": ["cs256", "cs1024"], "overlap": ["ov0", "ov25"], "top_k": ["k3", "k10"]}
    for pool in ("A_main", "B"):
        for metric in ("recall", "above"):
            b = out["knobs"][f"base|{pool}"][metric][0]
            eff = {ax: max((out["knobs"][f"{r}|{pool}"][metric][0] - b for r in rs), key=abs) for ax, rs in axes.items()}
            rank = " > ".join(sorted(eff, key=lambda a: -abs(eff[a])))
            out.setdefault("ranking", {})[f"{pool}|{metric}"] = {"effects": eff, "ranking": rank}
            L.append(f"| {pool} | {'raw recall' if metric == 'recall' else 'above random'} | "
                     + " | ".join(f"{100 * eff[a]:+.0f}" for a in axes) + f" | {rank} |")
    L.append("\nOne question in Tier A main moves recall by 3 points (1/33); in Tier B by 8 (1/13). Read every delta "
             "against the CIs in the knob table.")

    # ---------------- interaction check (sweep_plan formula), pool A_main, recall@5
    L.append("\n## Interaction check (sweep_plan.py formula; Tier A main, recall@5)\n")
    R = {rid: out["knobs"][f"{rid}|A_main"] for rid, _, _ in RUNS}
    for metric in ("recall", "above"):
        slope = (R["base"][metric][0] - R["ov0"][metric][0]) / (R["base"]["overlap_measured"] - R["ov0"]["overlap_measured"])
        for s in ("256", "1024"):
            direct = R[f"cs{s}_matched"][metric][0] - R["base"][metric][0]
            extra = (R[f"cs{s}"][metric][0] - R["base"][metric][0]) - slope * (R[f"cs{s}"]["overlap_measured"] - R["base"]["overlap_measured"])
            L.append(f"- {metric}, cs{s}: direct {100 * direct:+.1f} pts, extrapolated {100 * extra:+.1f} pts, "
                     f"gap {100 * (direct - extra):+.1f} pts (slope {100 * slope:.2f} pts per overlap point)")
            out.setdefault("interaction", {})[f"{metric}|{s}"] = {"direct": direct, "extrapolated": extra}
    L.append("- The 1024 pair differs in 2 of 64 chunks and is not independent evidence. The 256 pair is the single "
             "real observation (pre-registered framing).")

    # ---------------- A/B readout at base
    base = data["base"]
    B = {q["id"]: q for q in load_eval_set(ROOT / "eval/tier_b.jsonl")}
    cov, gold_only = set(), set()
    for q in B.values():
        cov |= gold_ids(q)
        gold_only |= gold_ids(q) - {(a["gold_file"], a["gold_section"]) for a in q.get("also_acceptable") or []}
        for g in _groups(q):
            cov |= g
    gold_only = {(q["gold_file"], q["gold_section"]) for q in B.values() if q["category"] not in ("unanswerable", "unsettled")}
    A_main = {r["id"]: r for r in base if r["pool"] == "A_main"}
    main_q = {f"A_main-{i:02d}": q for i, q in enumerate(load_eval_set(ROOT / "eval/tier_a.jsonl"))}
    top_q = {f"A_topup-{i:02d}": q for i, q in enumerate(load_eval_set(ROOT / "eval/tier_a_topup.jsonl"))}

    def sec(qq):
        return (qq["gold_file"], qq["gold_section"])

    def row(rs, rule, name):
        hit = [r[rule]["hit@5"] for r in rs]
        rr = [r[rule]["rr@5"] for r in rs]
        ranks = [r[rule]["rank"] for r in rs]
        out["ab"][f"{name}|{rule}"] = {"n": len(rs), "recall5": boot(hit), "mrr5": boot(rr),
                                       "median_rank": float(np.median(ranks)) if ranks else None}
        return f"| {name} | {rule} | {len(rs)} | {fmt(boot(hit))} | {fmt(boot(rr), False)} | {np.median(ranks):.0f} |"

    L.append("\n## Tier A vs Tier B at the base config (descriptive; language confound applies; see writeup_notes)\n")
    L.append("| set | rule | n | recall@5 | MRR@5 | median uncensored rank |")
    L.append("|---|---|---|---|---|---|")
    s3 = [r for r in base if r["pool"] == "A_main" and sec(main_q[r["id"]]) in cov] + \
         [r for r in base if r["pool"] == "A_topup" and sec(top_q[r["id"]]) in cov]
    s3g = [r for r in s3 if sec(main_q.get(r["id"]) or top_q[r["id"]]) in gold_only]
    sets = [("(1) Tier A main", list(A_main.values())), ("(2) Tier B", [r for r in base if r["pool"] == "B"]),
            ("(3) Tier A on Tier B sections", s3), ("(3g) sensitivity: gold-only sections", s3g)]
    for rule in ("strict", "lenient"):
        for name, rs in sets:
            L.append(row(scored(rs, rule), rule, name))
    L.append("\nstrict and lenient differ only for B14 (multi_section).")

    # ---------------- paired triads
    L.append("\n## Paired R / MC / ME (same fact, same gold; base config; descriptive; n is small)\n")
    P = {}
    for r in base:
        if r["pool"] in ("B", "A_paired") and "strict" in r:
            pid = r["id"] if r["pool"] == "B" else r["pair_of"]
            P.setdefault(pid, {})[r["variant"]] = r["strict"]["rank"]
    L.append("| pair | R rank | MC rank | ME rank |")
    L.append("|---|---|---|---|")
    for pid in sorted(P):
        v = P[pid]
        if len(v) > 1:
            L.append(f"| {pid} | {v.get('R')} | {v.get('MC', '-')} | {v.get('ME', '-')} |")
    tri = [v for v in P.values() if {"R", "MC", "ME"} <= set(v)]
    for a, b in (("R", "MC"), ("MC", "ME"), ("R", "ME")):
        pairs = [v for v in P.values() if a in v and b in v]
        h = [(v[a] <= 5, v[b] <= 5) for v in pairs]
        d = [np.log(v[a]) - np.log(v[b]) for v in pairs]
        out["paired"][f"{a}-{b}"] = {"n": len(pairs), "recall5": [float(np.mean([x for x, _ in h])), float(np.mean([y for _, y in h]))],
                                     "median_log_rank_diff": float(np.median(d))}
        L.append(f"\n- {a} vs {b}: n = {len(pairs)} pairs; recall@5 {a} {100 * np.mean([x for x, _ in h]):.0f}% vs "
                 f"{b} {100 * np.mean([y for _, y in h]):.0f}%; median rank {np.median([v[a] for v in pairs]):.0f} vs "
                 f"{np.median([v[b] for v in pairs]):.0f}; within-pair Spearman of ranks "
                 f"{np.corrcoef(np.argsort(np.argsort([v[a] for v in pairs])), np.argsort(np.argsort([v[b] for v in pairs])))[0, 1]:.2f}")
    L.append(f"\nComplete triads: {len(tri)}.")

    # ---------------- answers per config
    L.append("\n## Answers (Haiku 4.5) per config\n")
    L.append("| run | n answered | cite_gold strict (A_main) | cite_gold (B) | cite_valid | B02/B06 abstained | latency p50 / p95 ms | cost |")
    L.append("|---|---|---|---|---|---|---|---|")
    for rid, _, _ in RUNS:
        rs = [r for r in data[rid] if r.get("answer") is not None]
        cga = [r["cite_gold"]["strict"] for r in rs if r["pool"] == "A_main" and "cite_gold" in r]
        cgb = [r["cite_gold"]["strict"] for r in rs if r["pool"] == "B" and "cite_gold" in r]
        val = [r["cite_valid"] for r in rs]
        ab = [f"{r['id']}:{'Y' if r['abstained'] else 'N'}" for r in rs if r["id"] in ("B02", "B06")]
        lat = [r["latency_ms"] for r in rs]
        cost = sum(r["usage"]["in"] * 1.10 + r["usage"]["out"] * 5.50 for r in rs) / 1e6
        out["answers"][rid] = {"cite_gold_A": boot(cga), "cite_gold_B": boot(cgb), "cite_valid": float(np.mean(val)),
                               "abstain": ab, "lat_p50": float(np.percentile(lat, 50)), "lat_p95": float(np.percentile(lat, 95)),
                               "cost": cost}
        L.append(f"| {rid} | {len(rs)} | {fmt(boot(cga))} | {fmt(boot(cgb))} | {100 * np.mean(val):.0f}% | {' '.join(ab)} | "
                 f"{np.percentile(lat, 50):.0f} / {np.percentile(lat, 95):.0f} | ${cost:.4f} |")
    L.append("\nAbstention is measured under the prompt's explicit abstention instruction, so it is an upper bound.")
    (ROOT / "reports/sweep_results.md").write_text("\n".join(L) + "\n")
    (ROOT / "reports/sweep_results.json").write_text(json.dumps(out, indent=1, default=str))
    print("\n".join(L))


if __name__ == "__main__":
    main()
